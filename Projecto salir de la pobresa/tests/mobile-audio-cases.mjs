// Integration checks use a real AudioContext and real trusted CDP interactions.
// Native lifecycle callbacks are simulated explicitly; immersive bars need a device.
export async function runMobileAudioChecks({ call, evaluate, check, click, key, viewport, navigate, screenshot, delay }) {
  await viewport(390,844);
  await navigate('/?audio=reset');
  await evaluate('localStorage.clear()');
  await navigate('/?audio=initial');
  await check('Audio never autoplays or allocates a context on page load', 'audioManager.context===null && !audioManager.unlocked && audioManager.music===null');
  await click('#settingsBtn');
  await delay(200);
  await evaluate('(async()=>{if(audioManager.musicLoading)await audioManager.musicLoading;return true})()');
  await check('Trusted interaction unlocks actual Web Audio', 'audioManager.context?.state === "running" && audioManager.unlocked && audioManager.supported');
  await check('Original menu loop is rendered and playing', 'audioManager.music?.source.loop && audioManager.musicBuffer?.duration>19 && audioManager.musicBuffer.duration<20');
  await check('Music buffer has a nonzero, unclipped waveform', '(()=>{let sum=0,peak=0;for(const s of audioManager.musicBuffer.getChannelData(0)){sum+=s*s;peak=Math.max(peak,Math.abs(s));}return sum>1 && peak<1;})()');
  await evaluate('window.originalMenuBuffer=audioManager.musicBuffer');
  await click('#musicEnabled');
  await delay(120);
  await check('Music toggle stops only music', '!audioManager.options.musicEnabled && !audioManager.music && audioManager.options.effectsEnabled');
  await click('#musicEnabled');
  await check('Music toggle reuses original buffer', 'audioManager.music?.source.loop && audioManager.musicBuffer===window.originalMenuBuffer');
  await click('#effectsEnabled');
  await check('Effects toggle mutes SFX while keeping music', '!audioManager.options.effectsEnabled && !audioManager.play("button") && Boolean(audioManager.music)');
  await click('#effectsEnabled');
  await click('#masterVolume');
  await key('Home');
  await delay(120);
  await check('Zero master volume suspends all audio', 'preferences.masterVolume===0 && audioManager.context.state === "suspended" && !audioManager.music && audioManager.voices.size===0');
  await key('End');
  await delay(120);
  await check('Volume keyboard control restores audio and persists', 'preferences.masterVolume===1 && audioManager.context.state === "running" && JSON.parse(localStorage.getItem(preferencesKey)).masterVolume===1');
  await evaluate('masterVolumeInput.value=25;masterVolumeInput.dispatchEvent(new Event("input"));masterVolumeInput.dispatchEvent(new Event("change"))');
  await click('#musicEnabled');
  await click('#effectsEnabled');
  await navigate('/?audio=persisted');
  await check('All audio preferences survive reload without autoplay', '!preferences.musicEnabled && !preferences.effectsEnabled && preferences.masterVolume===0.25 && audioManager.context===null');
  await click('#settingsBtn');
  await click('#effectsEnabled');
  await click('#musicEnabled');
  await delay(200);
  await screenshot('after/audio-settings.png');
  await evaluate('preferences.tutorialSeen=true; savePreferences()');
  await click('#settingsBackBtn');
  await delay(120);
  await evaluate('window.menuSource=audioManager.music; window.menuBuffer=audioManager.musicBuffer');
  await click('#scoresBtn');
  await click('#scoresBackBtn');
  await click('#settingsBtn');
  await click('#settingsBackBtn');
  await check('Menu navigation never duplicates or restarts the same loop', 'audioManager.music === window.menuSource && audioManager.musicBuffer === window.menuBuffer');
  await click('#startBtn');
  await evaluate('stopAnimation(); state=newState(); updateHud()');
  await delay(120);
  await check('Starting a game fades out menu music', 'audioManager.scene==="game" && audioManager.music===null && running');
  await evaluate('window.soundCalls=[];window.soundAccepted=[];const originalPlay=audioManager.play.bind(audioManager);audioManager.play=(name,...args)=>{soundCalls.push(name);const result=originalPlay(name,...args);if(result)soundAccepted.push(name);return result;}');
  await key('ArrowLeft');
  await delay(70);
  await evaluate('window.soundCalls=[];window.soundAccepted=[]');
  await key('ArrowLeft');
  await check('Out-of-bounds movement produces no sound', 'state.lane===0 && soundCalls.length===0');
  await key('ArrowRight');
  await check('Valid keyboard movement emits exactly one movement effect', 'state.lane===1 && soundCalls.filter(n=>n==="move").length===1 && soundAccepted.filter(n=>n==="move").length===1');
  await delay(70);
  await evaluate('window.soundCalls=[];window.soundAccepted=[]');
  await click('#rightBtn');
  await check('Direction button has movement sound without duplicate click', 'state.lane===2 && soundCalls.length===1 && soundCalls[0]==="move"');
  await evaluate('window.soundCalls=[]; state.soldiers=18;state.bullets=[];shoot()');
  await check('An 18-soldier volley emits one sound and retains 18 bullets', 'state.bullets.length===18 && soundCalls.filter(n=>n==="shoot").length===1');
  await evaluate('window.soundAccepted=[];for(let i=0;i<200;i++)audioManager.play("shoot")');
  await check('Rapid shots are throttled with a single shot voice', 'soundAccepted.length<=1 && [...audioManager.voices].filter(v=>v.name==="shoot").length<=1');
  await evaluate('state=newState();window.soundCalls=[];window.soundAccepted=[];spawnEnemy("grunt",100);defeatEnemy(state.enemies[0]);defeatEnemy(state.enemies[0])');
  await check('Enemy defeat sounds once and preserves rewards', 'state.kills===1 && state.score===28 && soundCalls.filter(n=>n==="enemyDefeat").length===1 && soundAccepted.filter(n=>n==="enemyDefeat").length===1');
  await evaluate('state=newState();window.soundCalls=[];spawnEnemy("grunt",100);state.enemies[0].hp=5;state.bullets=[{lane:1,y:100,damage:1,target:"enemy"}];handleCollisions()');
  await check('Nonlethal enemy hit does not play defeat effect', 'state.kills===0 && state.enemies[0].hp===4 && !soundCalls.includes("enemyDefeat")');
  await evaluate('state=newState();window.soundCalls=[];hitAlly({y:0,damage:1})');
  await check('Fractional ally charge without displayed percentage change stays silent', 'state.allyCharge===1 && !soundCalls.includes("allyCharge")');
  await evaluate('state.allyCharge=7;window.soundCalls=[];window.soundAccepted=[];hitAlly({y:0,damage:1});window.lowChargeRate=[...audioManager.voices].find(v=>v.name==="allyCharge")?.source.playbackRate.value');
  await check('Increasing displayed ally percentage plays a soft charge sound', 'state.allyCharge===8 && soundCalls.filter(n=>n==="allyCharge").length===1 && soundAccepted.filter(n=>n==="allyCharge").length===1 && window.lowChargeRate>0');
  await delay(100);
  await evaluate('state.allyCharge=359;hitAlly({y:0,damage:1})');
  await check('Ally charge sound pitch rises with real progress', '[...audioManager.voices].find(v=>v.name==="allyCharge")?.source.playbackRate.value>window.lowChargeRate');
  await evaluate('window.soundCalls=[];state.allyCharge=100;for(let i=0;i<50;i++)hitAlly({y:0,damage:1})');
  await check('Rapid ally hits never accumulate multiple charge voices', '[...audioManager.voices].filter(v=>v.name==="allyCharge").length<=1');
  await evaluate('state.allyCharge=720;state.allyUnlocked=true;window.soundCalls=[];hitAlly({y:0,damage:10})');
  await check('Fully activated ally does not keep playing charge sounds', 'soundCalls.length===0 && state.allyCharge===720');
  await evaluate('window.soundCalls=[];state.health=3;takeDamage({type:"grunt",lane:1})');
  await check('Real damage emits one distinct effect and subtracts one life', 'state.health===2 && soundCalls.filter(n=>n==="damage").length===1');
  await evaluate('state.health=0;window.soundCalls=[];takeDamage({type:"grunt",lane:1})');
  await check('No damage sound when health cannot decrease', 'soundCalls.length===0');
  await evaluate('state=newState();state.soldiers=17;state.lane=0;state.pickups=[{lane:0,y:playerY(),kind:"soldier",amount:2,speed:0,size:30}];window.soundCalls=[];window.soundAccepted=[];handleCollisions();handleCollisions()');
  await check('Pickup at 17 reaches 18 and emits achievement once', 'state.soldiers===18 && soundCalls.filter(n=>n==="maxSoldiers").length===1 && soundAccepted.filter(n=>n==="maxSoldiers").length===1');
  await evaluate('audioManager.soldiersChanged(18,18,18); audioManager.soldiersChanged(18,18,18)');
  await check('Remaining at maximum soldiers never repeats achievement', 'soundCalls.filter(n=>n==="maxSoldiers").length===1');
  await evaluate('state.soldiers=16;state.allyCharge=719;hitAlly({y:0,damage:1})');
  await check('Reaching maximum again through ally emits a new achievement', 'state.soldiers===18 && state.allyUnlocked && soundAccepted.filter(n=>n==="maxSoldiers").length===2');
  await check('Active sound voices are bounded by effect type', 'audioManager.voices.size<=7 && new Set([...audioManager.voices].map(v=>v.name)).size===audioManager.voices.size');
  await check('All reused effects contain nonzero, bounded PCM samples', '[...audioManager.buffers.values()].every(b=>{const samples=b.getChannelData(0);return samples.some(s=>Math.abs(s)>0.01)&&samples.every(s=>Math.abs(s)<1);})');
  await click('#pauseBtn');
  await delay(100);
  await check('Pause stops gameplay audio and voices finish cleanly', 'paused && audioManager.scene==="paused" && !audioManager.music && audioManager.voices.size===0 && !audioManager.play("shoot")');
  await evaluate('window.pauseState=JSON.stringify(state);window.soundCalls=[]');
  await click('#pauseTutorialBtn');
  await delay(80);
  await check('Help from pause retains state and plays one button sound', 'JSON.stringify(state)===window.pauseState && audioManager.scene==="paused" && soundCalls.filter(n=>n==="button").length===1');
  await click('#tutorialDoneBtn');
  await click('#resumeBtn');
  await evaluate('stopAnimation()');
  await check('Resume restores audio scene without restarting game', '!paused && audioManager.scene==="game" && state.soldiers===18 && !audioManager.music');

  // Real browser visibility/focus change via a second tab, not an injected event.
  const other = await call('Target.createTarget', { url:'about:blank' });
  await call('Target.activateTarget', { targetId:other.targetId });
  await delay(250);
  await check('Background tab pauses game and suspends actual AudioContext', 'document.hidden && paused && audioManager.context.state==="suspended" && !audioManager.music && audioManager.voices.size===0');
  await call('Page.bringToFront');
  await call('Target.closeTarget', { targetId:other.targetId });
  await delay(150);
  await check('Returning to foreground keeps game paused and music silent', '!document.hidden && paused && !audioManager.music && audioManager.voices.size===0');
  await click('#pauseMenuBtn');
  await delay(150);
  await check('Returning to menu starts one reused music buffer', 'audioManager.scene==="menu" && audioManager.music?.source.loop && audioManager.musicBuffer===window.menuBuffer');
  await evaluate('startGame();stopAnimation();gameOver()');
  await delay(150);
  await check('Game-over scene does not leave a music loop or active effects', 'audioManager.scene==="results" && !audioManager.music && audioManager.voices.size===0');

  // Simulated native platform and App callbacks. This does not test Android bars.
  const nativeScript = await call('Page.addScriptToEvaluateOnNewDocument', { source: 'window.nativeCallbacks={};window.Capacitor={getPlatform:()=>"android",Plugins:{App:{addListener:(event,fn)=>{window.nativeCallbacks[event]=fn;return Promise.resolve({remove(){}});}}}};' });
  await navigate('/?audio=native');
  await click('#startBtn');
  await evaluate('stopAnimation();window.nativeCallbacks.appStateChange({isActive:false})');
  await delay(120);
  await check('Native background callback pauses gameplay and suspends audio', 'paused && audioManager.blockers.has("native") && audioManager.context.state==="suspended"');
  await evaluate('window.nativeCallbacks.appStateChange({isActive:true});window.orientationState=JSON.stringify(state)');
  await viewport(844,390);
  for (let attempt=0; attempt<30 && !await evaluate('orientationBlocked'); attempt++) await delay(30);
  await check('Short native landscape window presents existing-style guard', 'orientationBlocked && !orientationGuard.hidden && appEl.inert && paused && audioManager.blockers.has("orientation")');
  await evaluate('startGame();resumeGame()');
  await check('Orientation fallback cannot accidentally restart or resume', 'paused && JSON.stringify(state)===window.orientationState');
  await screenshot('after/orientation-fallback.png');
  await viewport(390,844);
  for (let attempt=0; attempt<30 && await evaluate('orientationBlocked'); attempt++) await delay(30);
  await check('Returning to portrait restores access and preserves paused state', '!orientationBlocked && orientationGuard.hidden && !appEl.inert && paused && JSON.stringify(state)===window.orientationState');
  await click('#resumeBtn');
  await evaluate('stopAnimation()');
  await check('Player can resume normally after orientation recovery', '!paused && running && !activeScreen');
  await call('Page.removeScriptToEvaluateOnNewDocument', { identifier:nativeScript.identifier });
  const noAudioScript = await call('Page.addScriptToEvaluateOnNewDocument', { source:'window.AudioContext=undefined;window.webkitAudioContext=undefined;' });
  await navigate('/?audio=unsupported');
  await click('#startBtn');
  await evaluate('stopAnimation()');
  await key('ArrowLeft');
  await check('Missing Web Audio degrades safely without blocking gameplay', '!audioManager.supported && running && state.lane===0 && !orientationBlocked');
  await call('Page.removeScriptToEvaluateOnNewDocument', { identifier:noAudioScript.identifier });
  await navigate('/?audio=complete');
}
